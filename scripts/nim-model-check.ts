/**
 * Diagnostic: which NVIDIA NIM model reliably returns KITT's structured schema?
 *
 * Runs the real orchestrator (not a mock) against each candidate model and
 * reports whether hardware actions were actually produced.
 *
 * Usage: npx tsx scripts/nim-model-check.ts
 */

import dotenv from 'dotenv';
dotenv.config();

import { KittOrchestrator } from '../src/services/orchestrator';
import { NimGeminiClient } from '../src/services/nimClient';
import { edgeFirmwareCompiler } from '../src/services/firmwareCompiler';

const MODELS = [
  'nvidia/nemotron-3-super-120b-a12b',
  'openai/gpt-oss-20b',
  'nvidia/nemotron-3.5-lightning-30b-a3b',
];

const QUERY =
  'Build a plant watering monitor with an ESP32 and a capacitive soil sensor. Include the LED indicator and a MOSFET pump drive.';

async function main() {
  const apiKey = process.env.NVIDIA_API_KEY;
  if (!apiKey) {
    console.error('NVIDIA_API_KEY is not set');
    process.exit(1);
  }

  for (const model of MODELS) {
    process.stdout.write(`\n=== ${model} ===\n`);
    const client = new NimGeminiClient(apiKey, model);
    const orchestrator = new KittOrchestrator(client, edgeFirmwareCompiler);

    const started = Date.now();
    try {
      const result = await orchestrator.handleCoreChatRequest({
        messages: [{ role: 'user', content: QUERY }],
        requestId: `diag_${Date.now()}`,
      });
      const elapsed = ((Date.now() - started) / 1000).toFixed(1);

      const actions = result.proposedPatch?.actions?.length ?? 0;
      const explanationIsDefault = result.reply.startsWith('Hardware action set generated by KITT Core.');

      console.log(`  model returned : ${result.model}`);
      console.log(`  latency        : ${elapsed}s`);
      console.log(`  isMock         : ${result.isMock}`);
      console.log(`  actions        : ${actions}`);
      console.log(`  default reply  : ${explanationIsDefault ? 'YES (schema rejected output)' : 'no'}`);
      console.log(`  bom items      : ${result.bom?.items?.length ?? 0}`);
      console.log(`  reply preview  : ${result.reply.replace(/\s+/g, ' ').slice(0, 140)}`);
    } catch (err: any) {
      console.log(`  FAILED: ${err?.message}`);
    }
  }
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
